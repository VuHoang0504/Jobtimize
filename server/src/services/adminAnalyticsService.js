const { executeQuery } = require('../config/db');

const DAY = 86400000;
const bad = message => Object.assign(new Error(message), { status: 400 });
const iso = date => date.toISOString().slice(0, 10);
const addDays = (date, count) => new Date(date.getTime() + count * DAY);
function parseDay(value) {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) throw bad('Ngày phải có định dạng YYYY-MM-DD.');
  const date = new Date(`${value}T00:00:00Z`);
  if (!Number.isFinite(date.getTime()) || iso(date) !== value || date.getUTCFullYear() < 2000 || date.getUTCFullYear() > 2100) throw bad('Ngày không hợp lệ (2000–2100).');
  return date;
}

function resolvePeriod(input = {}, now = new Date()) {
  // SQL DATETIME stores the application's Vietnam wall clock. Pass calendar strings,
  // rather than timezone-shifted JS Date parameters, for half-open date predicates.
  const today = parseDay(new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Ho_Chi_Minh', year: 'numeric', month: '2-digit', day: '2-digit' }).format(now));
  const mode = input.timeRange || '6m';
  let from, end, previousFrom, previousEnd;
  if (mode === 'day') {
    from = parseDay(input.date); end = addDays(from, 1);
  } else if (mode === 'month') {
    if (typeof input.month !== 'string' || !/^\d{4}-\d{2}$/.test(input.month)) throw bad('Tháng phải có định dạng YYYY-MM.');
    from = parseDay(`${input.month}-01`);
    end = new Date(Date.UTC(from.getUTCFullYear(), from.getUTCMonth() + 1, 1));
    previousFrom = new Date(Date.UTC(from.getUTCFullYear(), from.getUTCMonth() - 1, 1)); previousEnd = from;
  } else if (mode === 'year') {
    if (!/^\d{4}$/.test(String(input.year))) throw bad('Năm không hợp lệ.');
    from = parseDay(`${input.year}-01-01`); end = new Date(Date.UTC(Number(input.year) + 1, 0, 1));
    previousFrom = new Date(Date.UTC(Number(input.year) - 1, 0, 1)); previousEnd = from;
  } else if (mode === 'custom') {
    from = parseDay(input.fromDate); end = addDays(parseDay(input.toDate), 1);
  } else if (['7d', '30d', '6m', '1y'].includes(mode)) {
    end = addDays(today, 1);
    from = mode.endsWith('d') ? addDays(end, -Number(mode.slice(0, -1))) : new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth() - (mode === '6m' ? 5 : 11), 1));
  } else throw bad('Bộ lọc thời gian không hợp lệ.');
  const days = (end - from) / DAY;
  if (days < 1 || days > 1830) throw bad('Khoảng thời gian phải từ 1 ngày đến tối đa 5 năm.');
  previousEnd ||= from; previousFrom ||= addDays(from, -days);
  const granularity = mode === 'year' || days > 92 ? 'month' : 'day';
  const buckets = [];
  let cursor = granularity === 'month' ? new Date(Date.UTC(from.getUTCFullYear(), from.getUTCMonth(), 1)) : from;
  while (cursor < end) {
    const key = iso(cursor).slice(0, granularity === 'day' ? 10 : 7);
    buckets.push({ key, label: granularity === 'day' ? `${key.slice(8)}/${key.slice(5, 7)}` : `${key.slice(5)}/${key.slice(0, 4)}`, fullLabel: key });
    cursor = granularity === 'day' ? addDays(cursor, 1) : new Date(Date.UTC(cursor.getUTCFullYear(), cursor.getUTCMonth() + 1, 1));
  }
  return { mode, fromDate: iso(from), toDate: iso(addDays(end, -1)), toExclusive: iso(end), previousFrom: iso(previousFrom), previousToExclusive: iso(previousEnd), granularity, timezone: 'Asia/Ho_Chi_Minh', buckets };
}
const paramsFor = period => ({ From: period.fromDate, Until: period.toExclusive, Prev: period.previousFrom, PrevUntil: period.previousToExclusive });
const success = "p.Status='Success' AND p.PaidAt IS NOT NULL";
const paidRange = `${success} AND p.PaidAt>=@From AND p.PaidAt<@Until`;
const growth = (current, previous) => previous ? Math.round((current - previous) / previous * 1000) / 10 : null;

// These exact references are generated by server.js's original demo seed.
// Read them separately: a sample subscription must never become a verified payment.
const demoSource = `(SELECT SubID PaymentID,TransactionCode TransactionRef,EmployerID,PackageID,
  AmountPaid Amount,'Success' Status,PaymentMethod,CreatedAt,StartDate PaidAt
  FROM EmployerSubscriptions WHERE PaymentStatus='Completed' AND AmountPaid IS NOT NULL
  AND TransactionCode IN('TXN-202605-FPT01','TXN-202606-VNG02','TXN-202607-KMS03','TXN-202608-VAI04',
    'TXN-202609-SHP05','TXN-202609-GHT06','TXN-202610-CHT07','TXN-202610-FPT08'))`;
function resolveSource(input) {
  const key = input.dataSource || 'payments';
  if (!['payments', 'demo'].includes(key)) throw bad('Nguồn dữ liệu báo cáo không hợp lệ.');
  return { key, isDemo: key === 'demo', label: key === 'demo' ? 'Dữ liệu mẫu có sẵn' : 'Thanh toán đã xác nhận' };
}

async function analytics(input) {
  const period = resolvePeriod(input), params = paramsFor(period);
  const source = resolveSource(input);
  const revenueTable = source.isDemo ? demoSource : 'PaymentTransactions';
  const size = period.granularity === 'day' ? 10 : 7;
  const queries = [
    `SELECT CONVERT(char(${size}),p.PaidAt,126) AS [key],SUM(p.Amount) revenue,COUNT(*) orders FROM ${revenueTable} p WHERE ${paidRange} GROUP BY CONVERT(char(${size}),p.PaidAt,126)`,
    `SELECT CONVERT(char(${size}),u.CreatedAt,126) AS [key],COUNT(*) newUsers,
      SUM(CASE WHEN EXISTS_ROLE.IsCandidate=1 THEN 1 ELSE 0 END) newCandidates,
      SUM(CASE WHEN EXISTS_ROLE.IsEmployer=1 THEN 1 ELSE 0 END) newEmployers
      FROM Users u OUTER APPLY(SELECT MAX(CASE WHEN r.RoleName='Candidate' THEN 1 ELSE 0 END) IsCandidate,MAX(CASE WHEN r.RoleName='Employer' THEN 1 ELSE 0 END) IsEmployer FROM UserRoles ur JOIN Roles r ON r.RoleID=ur.RoleID WHERE ur.UserID=u.UserID) EXISTS_ROLE
      WHERE u.CreatedAt>=@From AND u.CreatedAt<@Until GROUP BY CONVERT(char(${size}),u.CreatedAt,126)`,
    `SELECT CONVERT(char(${size}),CreatedAt,126) AS [key],COUNT(*) jobs FROM JobPostings WHERE CreatedAt>=@From AND CreatedAt<@Until GROUP BY CONVERT(char(${size}),CreatedAt,126)`,
    `SELECT CONVERT(char(${size}),AppliedAt,126) AS [key],COUNT(*) applications FROM JobApplications WHERE AppliedAt>=@From AND AppliedAt<@Until GROUP BY CONVERT(char(${size}),AppliedAt,126)`,
    `SELECT sp.PackageID packageId,sp.PackageName packageName,sp.Price price,COUNT(*) subscriptionCount,SUM(p.Amount) totalRevenue FROM ${revenueTable} p JOIN SubscriptionPackages sp ON sp.PackageID=p.PackageID WHERE ${paidRange} GROUP BY sp.PackageID,sp.PackageName,sp.Price ORDER BY totalRevenue DESC`,
    `SELECT COALESCE(p.PaymentMethod,N'Không xác định') method,COUNT(*) count,SUM(p.Amount) totalAmount FROM ${revenueTable} p WHERE ${paidRange} GROUP BY p.PaymentMethod ORDER BY totalAmount DESC`,
    `SELECT c.CategoryID categoryId,COALESCE(c.CategoryName,N'Chưa phân loại') categoryName,COUNT(*) jobCount FROM JobPostings j LEFT JOIN JobCategories c ON c.CategoryID=j.CategoryID WHERE j.CreatedAt>=@From AND j.CreatedAt<@Until GROUP BY c.CategoryID,c.CategoryName ORDER BY jobCount DESC`,
    `SELECT COALESCE(NULLIF(Location,''),N'Chưa cập nhật') location,COUNT(*) jobCount FROM JobPostings WHERE CreatedAt>=@From AND CreatedAt<@Until GROUP BY Location ORDER BY jobCount DESC`,
    `SELECT
      (SELECT COALESCE(SUM(p.Amount),0) FROM ${revenueTable} p WHERE ${success}) totalRevenue,
      (SELECT COALESCE(SUM(p.Amount),0) FROM ${revenueTable} p WHERE ${success} AND p.PaidAt>=@Prev AND p.PaidAt<@PrevUntil) previousRevenue,
      (SELECT COUNT(*) FROM Users WHERE CreatedAt>=@Prev AND CreatedAt<@PrevUntil) previousUsers,
      (SELECT COUNT(*) FROM JobPostings WHERE CreatedAt>=@Prev AND CreatedAt<@PrevUntil) previousJobs,
      (SELECT COUNT(*) FROM Users WHERE CreatedAt<@From) openingUsers,
      (SELECT COUNT(*) FROM Users) totalUsers,
      (SELECT COUNT(DISTINCT ur.UserID) FROM UserRoles ur JOIN Roles r ON r.RoleID=ur.RoleID WHERE r.RoleName='Candidate') totalCandidates,
      (SELECT COUNT(*) FROM Employers) totalEmployers,
      (SELECT COUNT(*) FROM JobPostings) totalJobs,
      (SELECT COUNT(*) FROM JobApplications) totalApplications,
      (SELECT COALESCE(AVG(MatchScore),0) FROM JobApplications WHERE AppliedAt>=@From AND AppliedAt<@Until) avgMatchScore,
      (SELECT COUNT(DISTINCT p.EmployerID) FROM ${revenueTable} p WHERE ${paidRange} AND p.Amount>0) payingEmployers`
  ];
  queries.push(`SELECT COUNT(*) count,COALESCE(SUM(p.Amount),0) amount FROM ${demoSource} p WHERE ${paidRange}`);
  const results = await Promise.all(queries.map(query => executeQuery(query, params)));
  const maps = results.slice(0, 4).map(result => new Map(result.recordset.map(row => [row.key, row])));
  const overall = results[8].recordset[0];
  let cumulativeUsers = overall.openingUsers;
  const timeline = period.buckets.map(bucket => {
    const row = { ...bucket, revenue: 0, orders: 0, newUsers: 0, newCandidates: 0, newEmployers: 0, jobs: 0, applications: 0, ...maps[0].get(bucket.key), ...maps[1].get(bucket.key), ...maps[2].get(bucket.key), ...maps[3].get(bucket.key) };
    row.revenue = Number(row.revenue); cumulativeUsers += row.newUsers; row.cumulativeUsers = cumulativeUsers;
    return row;
  });
  const sum = field => timeline.reduce((total, row) => total + Number(row[field]), 0);
  const periodRevenue = sum('revenue');
  const kpi = { ...overall, totalRevenue: Number(overall.totalRevenue), periodRevenue, periodOrders: sum('orders'), periodNewUsers: sum('newUsers'), periodNewJobs: sum('jobs'), periodApplications: sum('applications'), arpu: overall.payingEmployers ? periodRevenue / overall.payingEmployers : 0,
    revenueGrowthRate: growth(periodRevenue, Number(overall.previousRevenue)), userGrowthRate: growth(sum('newUsers'), overall.previousUsers), jobGrowthRate: growth(sum('jobs'), overall.previousJobs) };
  const percentage = amount => periodRevenue ? Number((Number(amount) / periodRevenue * 100).toFixed(1)) : 0;
  const { buckets, ...metadata } = period;
  return { source, demoAvailable: { count: results[9].recordset[0].count, amount: Number(results[9].recordset[0].amount) }, period: metadata, kpi, timeline, packagesBreakdown: results[4].recordset.map(row => ({ ...row, price: Number(row.price), totalRevenue: Number(row.totalRevenue), percentage: percentage(row.totalRevenue) })), paymentMethodsBreakdown: results[5].recordset.map(row => ({ ...row, totalAmount: Number(row.totalAmount), percentage: percentage(row.totalAmount) })), jobsByCategory: results[6].recordset, jobsByLocation: results[7].recordset };
}

async function transactions(input, exporting = false) {
  const period = resolvePeriod(input);
  const source = resolveSource(input);
  const page = Number(input.page || 1), limit = Number(input.limit || 20);
  if (!Number.isSafeInteger(page) || page < 1 || !Number.isSafeInteger(limit) || limit < 1 || limit > 100) throw bad('Phân trang không hợp lệ.');
  const search = String(input.search || '').trim();
  if (search.length > 200) throw bad('Từ khóa tìm kiếm quá dài.');
  const method = input.paymentMethod && input.paymentMethod !== 'all' ? String(input.paymentMethod) : '';
  if (method.length > 50) throw bad('Phương thức không hợp lệ.');
  const params = { ...paramsFor(period), Search: `%${search.replace(/[\[\]%_]/g, char => `[${char}]`)}%`, Method: method, Offset: exporting ? 0 : (page - 1) * limit, Limit: exporting ? 50001 : limit };
  const where = `${paidRange} AND (@Method='' OR p.PaymentMethod=@Method) AND (e.CompanyName LIKE @Search OR p.TransactionRef LIKE @Search OR sp.PackageName LIKE @Search)`;
  const from = `FROM ${source.isDemo ? demoSource : 'PaymentTransactions'} p JOIN Employers e ON e.EmployerID=p.EmployerID JOIN SubscriptionPackages sp ON sp.PackageID=p.PackageID`;
  const rows = await executeQuery(`SELECT p.PaymentID subId,p.TransactionRef transactionCode,p.EmployerID employerId,e.CompanyName companyName,e.CompanyLogoUrl companyLogoUrl,p.PackageID packageId,sp.PackageName packageName,p.Amount amount,p.PaymentMethod paymentMethod,p.Status paymentStatus,CONVERT(varchar(23),p.PaidAt,126) startDate,p.CreatedAt createdAt ${from} WHERE ${where} ORDER BY p.PaidAt DESC,p.PaymentID DESC OFFSET @Offset ROWS FETCH NEXT @Limit ROWS ONLY`, params);
  if (exporting && rows.recordset.length > 50000) throw bad('Báo cáo vượt 50.000 giao dịch. Vui lòng thu hẹp khoảng thời gian.');
  const total = exporting ? rows.recordset.length : (await executeQuery(`SELECT COUNT(*) total ${from} WHERE ${where}`, params)).recordset[0].total;
  return { source, transactions: rows.recordset.map(row => ({ ...row, amount: Number(row.amount), paymentStatus: source.isDemo ? 'Demo' : row.paymentStatus })), pagination: { page, limit, total, totalPages: Math.ceil(total / limit) }, period };
}

function csv(rows) {
  const cell = value => {
    let text = String(value ?? '');
    if (typeof value !== 'number' && /^[\s\uFEFF]*[=+\-@\t\r]/.test(text)) text = `'${text}`;
    return `"${text.replace(/"/g, '""')}"`;
  };
  return '\uFEFF' + rows.map(row => row.map(cell).join(',')).join('\r\n');
}
module.exports = { resolvePeriod, analytics, transactions, csv };
