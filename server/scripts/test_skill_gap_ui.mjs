import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
process.env.PLAYWRIGHT_BROWSERS_PATH ||= path.resolve('.cache/ms-playwright');
const { chromium } = require('playwright');
const output = path.resolve('.cache/skill-gap-tests');
await fs.mkdir(output, { recursive: true });

test('dense CV job workspace: 0% jobs, paging, AI feedback, courses, CV changes, errors and mobile', { timeout: 90000 }, async () => {
  const browser = await chromium.launch();
  const errors = [], requests = [], aiRequests = [];
  let fail = false, failAI = false, delayAI = 0, emptyAICourses = false;
  const cvs = [{ cvId: 1, versionId: 101, title: 'CV Frontend', isPrimary: true, status: 'Ready', version: 2 }, { cvId: 2, versionId: 102, title: 'CV Backend', status: 'Ready', version: 1 }, { cvId: 3, versionId: 103, title: 'CV chờ xác nhận', status: 'NeedsReview', version: 1 }];
  const jobs = [{ JobID: 11, Title: 'Frontend Developer (React / TypeScript)', CompanyName: 'Công ty công nghệ An Việt', Location: 'Hà Nội', SalaryRange: '20 - 35 triệu', matchScore: 50, matchedCount: 2, missingMandatoryCount: 1, recommendationReason: 'Khớp 2 kỹ năng trong CV' }, { JobID: 12, Title: 'Java Backend Engineer', CompanyName: 'Product Studio', Location: 'Remote', SalaryRange: 'Thỏa thuận', matchScore: 0, matchedCount: 0, missingMandatoryCount: 2, recommendationReason: 'Cùng ngành nghề với kỹ năng trong CV' }, ...Array.from({ length: 26 }, (_, i) => ({ JobID: 100 + i, Title: ['Frontend Engineer', 'Web Developer', 'Software Engineer', 'Fullstack Developer'][i % 4], CompanyName: `Đội sản phẩm ${i + 1}`, Location: ['Hồ Chí Minh', 'Hà Nội', 'Remote'][i % 3], matchScore: 0, matchedCount: 0, missingMandatoryCount: 1, recommendationReason: 'Cùng ngành nghề với kỹ năng trong CV' }))];
  const missing = [{ skillId: 5, skillName: 'TypeScript', isMandatory: true, status: 'missing', nextStep: 'Xây dựng một ứng dụng quản lý công việc bằng TypeScript.' }, { skillId: 6, skillName: 'Node.js', isMandatory: false, status: 'missing', nextStep: 'Thực hành xây dựng API có kiểm thử.' }];
  const courses = [{ id: 'f8', Title: 'Node & ExpressJS', Provider: 'F8', Url: 'https://f8.edu.vn/courses/nodejs', Language: 'vi', skills: [missing[1]] }, { id: 'helsinki', Title: 'Full Stack Open: TypeScript', Provider: 'University of Helsinki', Url: 'https://fullstackopen.com/en/part9/', Language: 'en', skills: [missing[0]] }];
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
    await context.addInitScript(() => localStorage.setItem('jobtimize_token', 'synthetic-ui-token'));
    const page = await context.newPage(); page.setDefaultTimeout(10000);
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/**', async route => {
      const url = new URL(route.request().url()).pathname;
      let data = [];
      if (url === '/api/auth/me') data = { userId: 1, role: 'Candidate', fullName: 'Ứng viên kiểm thử', email: 'candidate@example.invalid' };
      else if (url === '/api/candidate/skill-gap/insights') {
        const input = route.request().postDataJSON(); aiRequests.push(input);
        const failure = failAI, delay = delayAI;
        if (delay) await new Promise(resolve => setTimeout(resolve, delay));
        if (failure) return route.fulfill({ status: 503, json: { success: false, message: 'AI tạm thời chưa sẵn sàng.' } }).catch(() => {});
        data = { status: 'Ready', summary: Number(input.cvId) === 1 ? 'CV có bằng chứng React.js và Git. Cần bổ sung TypeScript để đáp ứng yêu cầu bắt buộc; Node.js là kỹ năng ưu tiên.' : 'Nhận xét cho CV Backend.', requirements: [{ skillId: 1, skillName: 'React.js', status: 'matched', reason: 'Kinh nghiệm xây dựng giao diện phù hợp với công việc.', cvEvidence: 'Xây dựng giao diện quản lý tuyển dụng bằng ReactJS.', jobEvidence: 'Phát triển giao diện bằng React.', isMandatory: true }, ...missing.map(skill => ({ ...skill, reason: 'Chưa có bằng chứng trong CV.', jobEvidence: `${skill.skillName} trong yêu cầu tuyển dụng.` }))], learningPriorities: missing, recommendedCourses: courses };
        if (emptyAICourses) data.recommendedCourses = [];
        return route.fulfill({ json: { success: true, data } }).catch(() => {});
      } else if (url === '/api/candidate/skill-gap') {
        const input = route.request().postDataJSON(); requests.push(input);
        if (fail) return route.fulfill({ status: 503, json: { success: false, message: 'Chưa tải được kết quả phân tích. Vui lòng thử lại.' } });
        const selectedCV = cvs.find(cv => cv.cvId === Number(input.cvId || 1));
        const job = jobs.find(item => item.JobID === Number(input.jobId || 11));
        data = { status: selectedCV.status === 'Ready' ? 'Ready' : 'NotReady', selectedCV, cvs, jobs, categories: [{ categoryId: 1, name: 'Frontend Development' }], verifiedSkillCount: 2, unscoredCount: 0, analysis: { status: 'Ready', criteriaSource: 'employer', job, matchScore: selectedCV.cvId === 2 ? 25 : job.matchScore, matchedSkills: [{ skillId: 1, skillName: 'React.js', evidence: 'Xây dựng giao diện quản lý tuyển dụng bằng ReactJS.', isMandatory: true }, { skillId: 2, skillName: 'Git', evidence: 'Quản lý phiên bản và phối hợp qua Git.', isMandatory: false }], missingSkills: missing, recommendedCourses: courses } };
      } else if (url === '/api/jobs/12') {
        assert.equal(new URL(route.request().url()).searchParams.get('cvId'), '2');
        data = { ...jobs[1], requiredSkills: [], candidateContext: { candidateCVs: cvs.slice(0, 2).map(cv => ({ CVID: cv.cvId, Title: cv.title, IsPrimary: cv.isPrimary })), aiAnalysis: { status: 'Ready', matchScore: 25, summary: 'CV Backend', matchedSkills: [], missingSkills: [] } } };
      } else if (url === '/api/jobs/12/match') {
        assert.equal(new URL(route.request().url()).searchParams.get('cvId'), '2');
        data = { status: 'Ready', matchScore: 25, summary: 'CV Backend', matchedSkills: [], missingSkills: [] };
      } else if (url.includes('/notifications')) return route.fulfill({ json: { success: true, data: [], unreadCount: 0, total: 0 } });
      else if (url.includes('/cv-documents')) throw new Error('The workspace must not re-read CV files');
      return route.fulfill({ json: { success: true, data } });
    });
    await page.goto(`${process.env.SKILL_UI_BASE || 'http://127.0.0.1:3000'}/candidate/skill-gap`);
    await page.getByRole('heading', { name: 'Tìm việc phù hợp với CV', exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Nhận xét cho CV của bạn', exact: true }).waitFor();
    assert.equal(await page.locator('.skill-workspace svg').count(), 0);
    assert.equal(await page.locator('.skill-job-row').count(), 24);
    const inView = await page.locator('.skill-job-rows').evaluate(el => [...el.children].filter(row => row.getBoundingClientRect().top >= el.getBoundingClientRect().top && row.getBoundingClientRect().bottom <= el.getBoundingClientRect().bottom).length);
    assert.ok(inView >= 5, `Expected at least five jobs in view, found ${inView}`);
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Sau', exact: true }).click();
    assert.equal(await page.locator('.skill-job-row').count(), 4);
    await page.getByRole('button', { name: 'Trước', exact: true }).click();
    await page.getByLabel('Số việc mỗi trang', { exact: true }).selectOption('48');
    assert.equal(await page.locator('.skill-job-row').count(), 28);
    await page.getByRole('tab', { name: 'Đối chiếu kỹ năng', exact: true }).click();
    await page.getByRole('button', { name: 'TypeScript Bắt buộc', exact: true }).click();
    assert.equal(await page.getByRole('tab', { name: 'Kỹ năng & khóa học', exact: true }).getAttribute('aria-selected'), 'true');
    assert.equal(await page.locator('.skill-course').count(), 1);
    await page.getByLabel('Kỹ năng cần bổ sung', { exact: true }).selectOption('');
    await page.getByLabel('Ngôn ngữ', { exact: true }).selectOption('vi');
    assert.equal(await page.locator('.skill-course').count(), 1);
    await page.getByLabel('Ngôn ngữ', { exact: true }).selectOption('');
    await page.getByRole('tab', { name: 'Nhận xét AI', exact: true }).click();
    await page.getByLabel('CV dùng để đối chiếu', { exact: true }).selectOption('2');
    await page.getByText('Nhận xét cho CV Backend.', { exact: true }).waitFor();
    assert.equal(requests.at(-1).cvId, '2');
    assert.ok((await page.getByRole('link', { name: 'Xem tin và ứng tuyển', exact: true }).getAttribute('href')).endsWith('?cvId=2'));
    await page.getByLabel('CV dùng để đối chiếu', { exact: true }).selectOption('3');
    await page.getByRole('heading', { name: 'Chuẩn bị CV để tìm việc phù hợp' }).waitFor();
    assert.equal(await page.locator('.skill-detail').count(), 0);
    await page.getByLabel('CV dùng để đối chiếu', { exact: true }).selectOption('1');
    await page.getByRole('heading', { name: 'Nhận xét cho CV của bạn', exact: true }).waitFor();
    delayAI = 300;
    const delayedRequest = page.waitForRequest(request => request.url().endsWith('/skill-gap/insights') && request.postDataJSON()?.cvId === 2);
    await page.getByLabel('CV dùng để đối chiếu', { exact: true }).selectOption('2');
    await delayedRequest;
    delayAI = 0;
    await page.getByLabel('CV dùng để đối chiếu', { exact: true }).selectOption('1');
    await page.getByText('CV có bằng chứng React.js và Git. Cần bổ sung TypeScript để đáp ứng yêu cầu bắt buộc; Node.js là kỹ năng ưu tiên.', { exact: true }).waitFor();
    await page.waitForTimeout(350);
    assert.equal(await page.getByText('Nhận xét cho CV Backend.', { exact: true }).count(), 0);
    failAI = true;
    await page.getByRole('button', { name: /Product Studio/ }).click();
    await page.getByText('AI tạm thời chưa sẵn sàng.', { exact: true }).waitFor();
    assert.equal(await page.locator('.skill-detail-title > strong').innerText(), '0%');
    await page.getByRole('tab', { name: 'Đối chiếu kỹ năng', exact: true }).click();
    await page.getByRole('heading', { name: 'Kỹ năng có trong CV (2)', exact: true }).waitFor();
    failAI = false;
    emptyAICourses = true;
    await page.getByRole('tab', { name: 'Nhận xét AI', exact: true }).click();
    await page.getByRole('button', { name: 'Thử lại nhận xét AI', exact: true }).click();
    await page.getByRole('heading', { name: 'Nhận xét cho CV của bạn', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Kỹ năng & khóa học', exact: true }).click();
    assert.equal(await page.locator('.skill-course').count(), 2, 'Empty AI courses must not hide catalogue courses');
    await page.getByLabel('Ngôn ngữ', { exact: true }).selectOption('vi');
    await page.getByLabel('Nguồn học', { exact: true }).selectOption('University of Helsinki');
    await page.getByText('Bộ lọc hiện tại đang ẩn các nguồn học đã tìm được.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Bỏ bộ lọc khóa học', exact: true }).click();
    assert.equal(await page.locator('.skill-course').count(), 2);
    await page.getByRole('tab', { name: 'Nhận xét AI', exact: true }).click();
    await page.getByLabel('Vị trí hoặc công ty', { exact: true }).fill('Frontend');
    await page.getByLabel('Ngành nghề', { exact: true }).selectOption('1');
    await page.getByRole('button', { name: 'Lọc việc làm', exact: true }).click();
    await page.waitForFunction(() => location.search.includes('keyword=Frontend') && document.querySelector('.skill-columns')?.getAttribute('aria-busy') === 'false');
    assert.equal(requests.at(-1).categoryId, '1');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: /Product Studio/ }).click();
    await page.waitForFunction(() => location.search.includes('jobId=12') && document.querySelector('.skill-columns')?.getAttribute('aria-busy') === 'false');
    await page.getByRole('heading', { name: 'Nhận xét cho CV của bạn', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    fail = true;
    await page.getByLabel('CV dùng để đối chiếu', { exact: true }).selectOption('2');
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByRole('link', { name: 'Xem tin và ứng tuyển', exact: true }).count(), 0);
    fail = false;
    await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
    await page.getByText('25%', { exact: true }).waitFor();
    await page.reload();
    await page.getByText('25%', { exact: true }).waitFor();
    assert.equal(requests.at(-1).cvId, '2'); assert.equal(requests.at(-1).jobId, '12');
    assert.ok(aiRequests.length > 0);
    await page.getByRole('link', { name: 'Xem tin và ứng tuyển', exact: true }).click();
    await page.waitForURL('**/jobs/12?cvId=2');
    await page.getByText('CV Backend', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
