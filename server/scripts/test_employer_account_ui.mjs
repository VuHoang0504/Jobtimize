import { test } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
process.env.PLAYWRIGHT_BROWSERS_PATH ||= path.resolve('.cache/ms-playwright');
const { chromium } = require('playwright');
const output = path.resolve('.cache/employer-account-tests');
await fs.mkdir(output, { recursive: true });

test('employer settings save, create/change password, KYC state, candidate Google setup and mobile', { timeout: 90000 }, async () => {
  const browser = await chromium.launch();
  let role = 'Employer', hasPassword = false, failSave = false;
  const writes = [], passwords = [], errors = [];
  let profile = { FullName: 'Nguyễn Minh An', Email: 'employer@example.invalid', Phone: '', CompanyName: 'Công ty An Việt', Website: 'https://example.org', CompanySize: '50–100 nhân viên', Address: 'Hà Nội', Description: 'Công ty phát triển sản phẩm công nghệ.', CompanyLogoUrl: '', KYCStatus: 'Pending', HasKycDocument: false };
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addInitScript(() => localStorage.setItem('jobtimize_token', 'synthetic-account-ui'));
    const page = await context.newPage(); page.setDefaultTimeout(10000); page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url()).pathname;
      let data = [];
      if (url === '/api/auth/me') data = { userId: 1, role, fullName: profile.FullName, email: profile.Email, hasPassword, googleLinked: true, profile };
      else if (url === '/api/employer/profile' && req.method() === 'PUT') {
        const body = req.postDataJSON(); writes.push(body);
        if (failSave) return route.fulfill({ status: 503, json: { success: false, message: 'Chưa lưu được hồ sơ. Vui lòng thử lại.' } });
        for (const [field, column] of Object.entries({ fullName: 'FullName', phone: 'Phone', companyName: 'CompanyName', website: 'Website', companySize: 'CompanySize', address: 'Address', description: 'Description', companyLogoUrl: 'CompanyLogoUrl' })) profile[column] = body[field];
        data = profile;
      } else if (url === '/api/employer/profile') data = profile;
      else if (url === '/api/auth/change-password') {
        const body = req.postDataJSON(); passwords.push(body);
        if (hasPassword && body.currentPassword !== 'SyntheticPass8') return route.fulfill({ status: 400, json: { success: false, message: 'Mật khẩu hiện tại không chính xác' } });
        const creating = !hasPassword; hasPassword = true;
        return route.fulfill({ json: { success: true, message: creating ? 'Tạo mật khẩu thành công! Bạn có thể đăng nhập bằng email và mật khẩu.' : 'Đổi mật khẩu thành công!', data: { hasPassword: true } } });
      } else if (url === '/api/employer/subscription') data = null;
      else if (url === '/api/candidate/profile') data = { FullName: profile.FullName, Email: profile.Email, cvs: [] };
      else if (url.includes('/notifications')) return route.fulfill({ json: { success: true, data: [], unreadCount: 0, total: 0 } });
      return route.fulfill({ json: { success: true, data } });
    });
    const base = process.env.ACCOUNT_UI_BASE || 'http://127.0.0.1:3000';
    await page.goto(`${base}/employer/dashboard`);
    await page.getByText('Chưa xác thực', { exact: true }).waitFor();
    await page.getByRole('link', { name: 'Hồ sơ & bảo mật', exact: true }).click();
    await page.getByRole('heading', { name: 'Hồ sơ & bảo mật', exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Tạo mật khẩu', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Mật khẩu hiện tại', { exact: true }).count(), 0);
    assert.equal(await page.getByLabel('Email đăng nhập', { exact: true }).getAttribute('readonly'), '');
    await page.getByLabel('Họ tên người liên hệ', { exact: true }).fill('Nguyễn Minh Anh');
    await page.getByLabel('Tên doanh nghiệp', { exact: true }).fill('Công ty Sản phẩm An Việt');
    await page.getByLabel('Website', { exact: true }).fill('');
    failSave = true;
    await page.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByLabel('Tên doanh nghiệp', { exact: true }).inputValue(), 'Công ty Sản phẩm An Việt');
    failSave = false;
    await page.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click();
    await page.getByText('Đã lưu hồ sơ doanh nghiệp.', { exact: true }).waitFor();
    assert.equal(writes.at(-1).website, ''); assert.equal(writes.at(-1).KYCStatus, undefined);
    assert.equal(profile.KYCStatus, 'Pending');
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    await page.getByLabel('Mật khẩu mới', { exact: true }).fill('SyntheticPass8');
    await page.getByLabel('Xác nhận mật khẩu mới', { exact: true }).fill('MismatchPass1');
    await page.getByRole('button', { name: 'Tạo mật khẩu', exact: true }).click();
    await page.getByText('Mật khẩu xác nhận chưa khớp.', { exact: true }).waitFor();
    assert.equal(passwords.length, 0);
    await page.getByLabel('Xác nhận mật khẩu mới', { exact: true }).fill('SyntheticPass8');
    await page.getByRole('button', { name: 'Tạo mật khẩu', exact: true }).click();
    await page.getByLabel('Mật khẩu hiện tại', { exact: true }).waitFor();
    assert.equal(passwords[0].currentPassword, undefined);
    await page.getByLabel('Mật khẩu hiện tại', { exact: true }).fill('wrong');
    await page.getByLabel('Mật khẩu mới', { exact: true }).fill('SyntheticPass9');
    await page.getByLabel('Xác nhận mật khẩu mới', { exact: true }).fill('SyntheticPass9');
    await page.getByRole('button', { name: 'Đổi mật khẩu', exact: true }).click();
    await page.getByText('Mật khẩu hiện tại không chính xác', { exact: true }).waitFor();
    await page.getByLabel('Mật khẩu hiện tại', { exact: true }).fill('SyntheticPass8');
    await page.getByRole('button', { name: 'Đổi mật khẩu', exact: true }).click();
    await page.getByText('Đổi mật khẩu thành công!', { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.reload();
    await page.getByLabel('Mật khẩu hiện tại', { exact: true }).waitFor();
    role = 'Candidate'; hasPassword = false;
    await page.goto(`${base}/candidate/dashboard?tab=security`);
    await page.getByRole('heading', { name: 'Tạo mật khẩu', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Mật khẩu hiện tại', { exact: true }).count(), 0);
    await page.getByLabel('Mật khẩu mới', { exact: true }).fill('SyntheticPass8');
    await page.getByLabel('Xác nhận mật khẩu mới', { exact: true }).fill('SyntheticPass8');
    await page.getByRole('button', { name: 'Tạo mật khẩu', exact: true }).click();
    await page.getByLabel('Mật khẩu hiện tại', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
