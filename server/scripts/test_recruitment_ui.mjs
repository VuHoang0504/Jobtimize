import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
process.env.PLAYWRIGHT_BROWSERS_PATH ||= path.resolve('.cache/ms-playwright');
const { chromium } = require('playwright');
const output = path.resolve('.cache/recruitment-tests'); await fs.mkdir(output, { recursive: true });

test('recruitment screens: employer review, invitation, schedule, candidate responses, bell links and mobile', { timeout: 90000 }, async () => {
  const browser = await chromium.launch();
  let role = 'Employer', failSchedule = false, failConfirmation = false, failNotice = false;
  const writes = [], errors = [];
  const job = { JobID: 7, Title: 'Chuyên viên phát triển sản phẩm', Status: 'Published', TotalApplicants: 1, NewApplicants: 1, CreatedAt: new Date().toISOString(), Location: 'Hồ Chí Minh' };
  const applicant = { ApplicationID: 20, JobID: 7, FullName: 'Nguyễn Minh Anh', Email: 'anh@example.org', Headline: 'Frontend Developer', Status: 'Applied', AppliedAt: new Date().toISOString(), MatchScore: null, CVTitle: 'CV áº£nh lá»—i', Bio: JSON.stringify({ bioText: '', links: {}, skills: { hardSkills: [] } }), CVFileUrl: '/api/cv-documents/applications/20/file' };
  const invite = { InvitationID: 30, ProfileID: 40, JobID: 7, Title: job.Title, JobTitle: job.Title, CompanyName: 'Công ty Sản phẩm An Việt', CandidateName: applicant.FullName, CandidateEmail: applicant.Email, Status: 'Sent', JobStatus: 'Published', Message: 'Mời bạn tìm hiểu cơ hội làm việc cùng đội ngũ sản phẩm.', SentAt: new Date().toISOString(), Version: 1 };
  const interviews = [];
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addInitScript(() => localStorage.setItem('jobtimize_token', 'synthetic-recruitment-ui'));
    const page = await context.newPage(); page.setDefaultTimeout(10000); page.on('pageerror', e => errors.push(e.message));
    await page.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url()).pathname, method = req.method(); let data = [];
      if (url === '/api/auth/me') data = { userId: 1, role, fullName: 'Nguyễn Minh Anh', email: 'anh@example.org' };
      else if (url === '/api/employer/profile') data = { CompanyName: invite.CompanyName, KYCStatus: 'Approved' };
      else if (url === '/api/employer/jobs') data = [job];
      else if (url === '/api/employer/subscription') data = null;
      else if (url === '/api/employer/jobs/7/ats') data = { job, applicants: [applicant] };
      else if (url.endsWith('/applications/20/status')) { const body = req.postDataJSON(); writes.push(body); if (body.status === 'Offered' && failConfirmation) return route.fulfill({ status: 503, json: { success: false, message: 'Chưa gửi được xác nhận. Vui lòng thử lại.' } }); applicant.Status = body.status; return route.fulfill({ json: { success: true, message: 'Đã cập nhật hồ sơ. Đã gửi email cho ứng viên.' } }); }
      else if (url === '/api/employer/applications/20/email') {
        writes.push(req.postDataJSON());
        if (failNotice) return route.fulfill({ status: 502, json: { success: false, message: 'Chưa gửi được email. Vui lòng thử lại.' } });
        return route.fulfill({ json: { success: true, message: 'Đã gửi thông báo qua email cho ứng viên.' } });
      }
      else if (url === '/api/employer/invitations') data = [invite];
      else if (url === '/api/employer/candidates') data = [{ ProfileID: 40, FullName: applicant.FullName, Email: applicant.Email, Headline: applicant.Headline }];
      else if (url === '/api/employer/invite-candidate') { writes.push(req.postDataJSON()); return route.fulfill({ json: { success: true, message: 'Đã gửi lời mời.' } }); }
      else if (url === '/api/employer/interviews' && method === 'POST') {
        const body = req.postDataJSON(); writes.push(body);
        if (failSchedule) return route.fulfill({ status: 409, json: { success: false, message: 'Lịch đã thay đổi. Vui lòng tải lại trước khi hẹn.' } });
        const interview = { InterviewID: 50, InvitationID: body.invitationId || null, ApplicationID: body.applicationId || null, InterviewDate: body.interviewDate, InterviewType: body.interviewType, LocationOrLink: body.locationOrLink, Notes: body.notes, Status: 'Pending', Version: 1, JobTitle: job.Title, CompanyName: invite.CompanyName, EmployerEmail: 'hr@example.org' };
        interviews.splice(0, interviews.length, interview);
        if (body.applicationId) { applicant.interview = interview; applicant.Status = 'Interviewing'; }
        else Object.assign(invite, { InterviewID: 50, InterviewDate: interview.InterviewDate, InterviewType: interview.InterviewType, LocationOrLink: interview.LocationOrLink, Notes: interview.Notes, InterviewStatus: 'Pending', InterviewVersion: 1 });
        return route.fulfill({ json: { success: true, message: 'Đã lưu lịch, chờ ứng viên xác nhận.', data: interview } });
      } else if (url === '/api/candidate/profile') data = { FullName: applicant.FullName, Email: applicant.Email, cvs: [], IsLookingForJob: true };
      else if (url === '/api/candidate/applications') data = [{ ...applicant, JobTitle: job.Title, CompanyName: invite.CompanyName }];
      else if (url === '/api/candidate/invitations') return route.fulfill({ json: { success: true, data: [invite], page: 1, hasMore: false } });
      else if (url === '/api/candidate/invitations/30/respond') { const body = req.postDataJSON(); writes.push(body); invite.Status = body.status; return route.fulfill({ json: { success: true, message: 'Đã ghi nhận quan tâm.' } }); }
      else if (url === '/api/candidate/interviews') data = interviews;
      else if (url === '/api/candidate/interviews/50/respond') { const body = req.postDataJSON(); writes.push(body); interviews[0].Status = body.status; return route.fulfill({ json: { success: true, message: 'Đã xác nhận tham gia phỏng vấn.' } }); }
      else if (url === '/api/notifications') return route.fulfill({ json: { success: true, data: [{ id: 1, title: 'Lời mời ứng tuyển', body: invite.CompanyName, href: role === 'Employer' ? '/employer/talents?tab=invitations&invitationId=30' : '/candidate/dashboard?tab=invitations&invitationId=30', createdAt: new Date().toISOString(), readAt: null }], total: 1, unread: 1 } });
      return route.fulfill({ json: { success: true, data } });
    });
    const base = process.env.RECRUITMENT_UI_BASE || 'http://127.0.0.1:3000';
    await page.goto(`${base}/employer/dashboard`);
    await page.getByRole('link', { name: 'Xét duyệt hồ sơ (1)' }).click();
    await page.getByRole('heading', { name: applicant.FullName, exact: true }).waitFor();
    const applicationCard = page.locator('#application-20');
    const cardText = await applicationCard.innerText();
    assert.equal(cardText.includes(applicant.CVTitle), false, 'Do not display corrupt legacy CV titles');
    assert.equal(cardText.includes('bioText'), false, 'Do not expose structured profile JSON');
    assert.equal(cardText.includes('Mức độ phù hợp'), false, 'Keep the review card focused on essential information');
    await applicationCard.getByRole('button', { name: 'Xem CV', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Duyệt vào xét tuyển', exact: true }).click();
    await page.getByText('Đang xét duyệt', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'employer-applications-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Hẹn phỏng vấn', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel(/Ngày giờ phỏng vấn/).fill('2028-11-02T10:30');
    assert.equal(await dialog.getByLabel('Đường dẫn cuộc họp').inputValue(), '');
    await dialog.getByLabel('Đường dẫn cuộc họp').fill('https://example.org/real-meeting');
    failSchedule = true;
    await dialog.getByRole('button', { name: 'Gửi lịch phỏng vấn', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    assert.equal(await dialog.getByLabel('Đường dẫn cuộc họp').inputValue(), 'https://example.org/real-meeting');
    failSchedule = false;
    await dialog.getByRole('button', { name: 'Gửi lịch phỏng vấn', exact: true }).click();
    await dialog.getByRole('button', { name: 'Hoàn tất', exact: true }).click();
    assert.ok(writes.find(w => w.applicationId === 20 && w.interviewDate.endsWith('Z')));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'employer-applications-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 1440, height: 1000 });
    const confirmationsBefore = writes.filter(write => write.status === 'Offered').length;
    await page.getByRole('button', { name: 'Xác nhận ứng tuyển', exact: true }).click();
    const confirmationModal = page.getByRole('dialog', { name: 'Gửi xác nhận ứng tuyển?' });
    await confirmationModal.waitFor();
    await confirmationModal.getByText(applicant.FullName, { exact: true }).waitFor();
    await confirmationModal.getByText(applicant.Email, { exact: true }).waitFor();
    await confirmationModal.getByText(job.Title, { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Quay lại');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Gửi xác nhận');
    await page.screenshot({ path: path.join(output, 'application-confirmation-dialog-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'application-confirmation-dialog-mobile.png') });
    assert.equal(await confirmationModal.evaluate(element => element.scrollWidth > element.clientWidth), false);
    await confirmationModal.getByRole('button', { name: 'Quay lại', exact: true }).click();
    assert.equal(writes.filter(write => write.status === 'Offered').length, confirmationsBefore, 'Cancel must not send a confirmation');
    await page.getByRole('button', { name: 'Xác nhận ứng tuyển', exact: true }).click();
    await page.keyboard.press('Escape');
    assert.equal(await confirmationModal.count(), 0);
    assert.equal(writes.filter(write => write.status === 'Offered').length, confirmationsBefore);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: 'Xác nhận ứng tuyển', exact: true }).click();
    failConfirmation = true;
    await confirmationModal.getByRole('button', { name: 'Gửi xác nhận', exact: true }).click();
    await confirmationModal.getByRole('alert').waitFor();
    assert.equal(await confirmationModal.isVisible(), true, 'Keep the dialog open after a failed request');
    failConfirmation = false;
    await confirmationModal.getByRole('button', { name: 'Gửi xác nhận', exact: true }).click();
    await page.getByText('Đã xác nhận ứng tuyển', { exact: true }).waitFor();
    assert.equal(await confirmationModal.count(), 0);
    assert.equal(writes.filter(write => write.status === 'Offered').length, confirmationsBefore + 2);
    await page.getByRole('button', { name: 'Gửi thông báo mới', exact: true }).click();
    const notice = page.getByRole('dialog', { name: 'Gửi thông báo mới', exact: true });
    await notice.getByText(applicant.Email, { exact: true }).waitFor();
    assert.equal(await notice.getByRole('button', { name: 'Gửi email', exact: true }).isDisabled(), true);
    await notice.getByLabel('Tiêu đề email').fill('Hướng dẫn các bước tiếp theo');
    await notice.getByLabel('Nội dung email').fill('Chào bạn, vui lòng liên hệ công ty để trao đổi các bước tiếp theo.');
    await page.screenshot({ path: path.join(output, 'application-notice-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'application-notice-mobile.png') });
    assert.equal(await notice.evaluate(element => element.scrollWidth > element.clientWidth), false);
    failNotice = true;
    await notice.getByRole('button', { name: 'Gửi email', exact: true }).click();
    await notice.getByRole('alert').waitFor();
    assert.ok((await notice.getByLabel('Nội dung email').inputValue()).includes('vui lòng liên hệ công ty'));
    failNotice = false;
    await notice.getByRole('button', { name: 'Gửi email', exact: true }).click();
    await notice.getByRole('status').waitFor();
    await notice.getByRole('button', { name: 'Hoàn tất', exact: true }).click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    role = 'Candidate';
    await page.goto(`${base}/candidate/dashboard?tab=applications`);
    await page.getByText('Trạng thái: Ứng tuyển thành công, kiểm tra email', { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, 'candidate-application-confirmation-mobile.png'), fullPage: true });
    role = 'Employer'; await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`${base}/employer/talents`);
    await page.getByRole('button', { name: 'Gửi lời mời ứng tuyển', exact: true }).click();
    await page.getByRole('dialog').getByRole('combobox').selectOption('7');
    await page.getByRole('dialog').getByRole('button', { name: 'Gửi lời mời', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Hoàn tất' }).click();
    await page.getByRole('button', { name: /Thông báo/ }).click();
    await page.getByRole('region', { name: 'Danh sách thông báo' }).getByRole('button', { name: /Lời mời ứng tuyển/ }).click();
    await page.getByRole('heading', { name: 'Lời mời đã gửi', exact: true }).waitFor();
    assert.ok(page.url().includes('invitationId=30'));
    role = 'Candidate';
    await page.goto(`${base}/candidate/dashboard?tab=invitations&invitationId=30`);
    await page.getByRole('button', { name: 'Quan tâm', exact: true }).click();
    await page.getByText('Đã ghi nhận quan tâm.', { exact: true }).waitFor();
    assert.equal(writes.at(-1).version, 1);
    role = 'Employer'; await page.goto(`${base}/employer/talents?tab=invitations&invitationId=30`);
    await page.getByRole('button', { name: 'Hẹn phỏng vấn', exact: true }).click();
    await page.getByRole('dialog').getByLabel(/Ngày giờ phỏng vấn/).fill('2028-11-02T14:30');
    await page.getByRole('dialog').getByLabel('Hình thức').selectOption('Offline');
    await page.getByRole('dialog').getByLabel('Địa điểm phỏng vấn').fill('Phòng 201, văn phòng An Việt');
    await page.getByRole('dialog').getByLabel('Hướng dẫn & thông tin liên hệ').fill('Liên hệ hr@example.org để hẹn lại.');
    await page.getByRole('dialog').getByRole('button', { name: 'Gửi lịch phỏng vấn' }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Hoàn tất' }).click();
    await page.screenshot({ path: path.join(output, 'employer-invitations-desktop.png'), fullPage: true });
    role = 'Candidate'; await page.goto(`${base}/candidate/dashboard?tab=invitations&interviewId=50`);
    await page.getByRole('button', { name: 'Xác nhận tham gia', exact: true }).click();
    await page.getByText('Đã xác nhận', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'candidate-invitations-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'candidate-invitations-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.equal(await page.locator('main').innerText().then(t => /UC-[A-Z]|Sinh Meet/.test(t)), false);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
